"""Local qualification only. Does not prepare a publication-ready artifact."""
import argparse,copy,json,os,pathlib,shutil,subprocess,hashlib
p=pathlib.Path(__file__).resolve().parent
root=p.parent.parent
parser=argparse.ArgumentParser()
parser.add_argument('--bindgen',required=True)
a=parser.parse_args()
subprocess.run([shutil.which('python'),str(p/'verify-dependencies.py')],cwd=root,check=True)
target=pathlib.Path(os.environ['CARGO_TARGET_DIR'])
assert target.is_absolute(),'CARGO_TARGET_DIR must be absolute'
assert subprocess.check_output([a.bindgen,'--version']).decode().strip()=='wasm-bindgen 0.2.127'
build_env=dict(os.environ)
cargo_home=pathlib.Path(os.environ.get('CARGO_HOME',str(pathlib.Path.home()/'.cargo'))).resolve()
build_env.pop('RUSTFLAGS',None)
build_env['CARGO_ENCODED_RUSTFLAGS']='\x1f'.join(['--remap-path-prefix='+str(root)+'=/racket','--remap-path-prefix='+str(cargo_home)+'=/cargo'])
for arguments in [
    ['--release','--target','wasm32-unknown-unknown','--lib'],
    ['--bin','racket-workbench-cli'],
]:
    command_env=dict(build_env)
    if '--target' in arguments: command_env['CARGO_ENCODED_RUSTFLAGS']+='\x1f-C\x1flink-arg=--max-memory=67108864'
    subprocess.run(['cargo','+1.95.0','build','--manifest-path',str(p/'Cargo.toml'),'--locked',*arguments],cwd=root,env=command_env,check=True)
site=root/'target/racket-prototype/RACKET/workbench'
site.mkdir(parents=True,exist_ok=True)
for name in ['index.html','style.css','app.js','worker.js']:
    shutil.copyfile(p/'web'/name,site/name)
shutil.copyfile(p/'fixtures/snapshot.json',site/'snapshot.json')
subprocess.run([a.bindgen,'--target','web','--out-dir',str(site/'pkg'),'--out-name','racket_workbench',str(target/'wasm32-unknown-unknown/release/racket_workbench.wasm')],check=True)
f=json.loads((p/'fixtures/snapshot.json').read_text())
cases=[json.dumps(f),'','{}','{','null']
for actions in [[],f['actions'][:1],f['actions'][1:],f['actions']*2]:
    v=copy.deepcopy(f);v['actions']=actions;cases.append(json.dumps(v))
for role in ['Surface','Zone','Actor','Prop','Hud','Text','Media','Control','Boundary','Camera']:
    v=copy.deepcopy(f);v['scene'][0]['role']=role;cases.append(json.dumps(v))
for width in [-2147483649,-2147483648,-1,0,2147483647,2147483648,1.5]:
    v=copy.deepcopy(f);v['scene'][0]['width']=width;cases.append(json.dumps(v))
for kind in ['Legal','Unavailable','GuidedIllegal','Destructive','Diagnostic']:
    v=copy.deepcopy(f);v['actions'][0]['availability']={'kind':kind,'unexpected':True};cases.append(json.dumps(v))
for key in ['actions','scene']:
    v=copy.deepcopy(f);v[key]=[v[key][0]]*257;cases.append(json.dumps(v))
for key in ['experience_id','surface']:
    v=copy.deepcopy(f);v['metadata'][key]='Terminal' if key=='surface' else 'different';cases.append(json.dumps(v))
cases+=[' '*131073,'\ufeff'+json.dumps(f),json.dumps(f,indent=2).replace('\n','\r\n')]
cli=target/'debug'/('racket-workbench-cli.exe' if os.name=='nt' else 'racket-workbench-cli')
receipts=[]
requests=[(text,'3') for text in cases]+[(json.dumps(f),frames) for frames in ['0','1','32','33','-1','1.5','','4294967296']]
for text,frames in requests:
    result=subprocess.run([str(cli),frames],input=text.encode('utf-8'),capture_output=True,check=True)
    receipts.append({'input':text,'frames':frames,'output':result.stdout.decode('utf-8').rstrip('\r\n')})
# Independent pre-existing native proof totals, not goldens generated by this adapter.
proof=json.loads((root/'crates/racket-core/tests/fixtures/runtime-proof.json').read_text())
controls=[]
for name in ['accepted','rejected']:
    v=copy.deepcopy(f)
    availability={'kind':'Legal'} if name=='accepted' else {'kind':'Unavailable','reason':'The product disabled this action.'}
    v['actions']=[{'id':'serve','label':'Serve','command':'serve','availability':availability}]
    v['scene']=[v['scene'][0]];v['scene'][0]['role']='Surface';v['scene'][0]['unsupported_features']=[]
    v['scene'][0]['provenance']={'class':'ProductAuthored','source_id':'racket:proof:scene'}
    text=json.dumps(v)
    output=subprocess.run([str(cli),'2'],input=text.encode(),capture_output=True,check=True).stdout.decode().rstrip('\r\n')
    report=json.loads(output);runtime=report['runtime']
    actual={'completed':runtime['completed'],'frameCount':len(runtime['frames']),'readyFrameCount':runtime['ready_frame_count'],'diagnostics':runtime['diagnostics']}
    assert actual==proof[name],(name,actual,proof[name])
    controls.append({'name':name,'input':text,'frames':'2','expected':proof[name]})
    receipts.append({'input':text,'frames':'2','output':output})
cache=p/'.cache';cache.mkdir(exist_ok=True)
(cache/'native-proof-controls.json').write_text(json.dumps(controls,indent=2)+'\n')
(cache/'native-cases.json').write_text(json.dumps(receipts))
wasm=site/'pkg/racket_workbench_bg.wasm'
receipt={'prototype_only':True,'native_cases':len(receipts),'wasm_bytes':wasm.stat().st_size,'wasm_sha256':hashlib.sha256(wasm.read_bytes()).hexdigest()}
(cache/'prototype-build.json').write_text(json.dumps(receipt,indent=2)+'\n')
print(json.dumps(receipt))
